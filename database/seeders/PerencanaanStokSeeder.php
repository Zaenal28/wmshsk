        foreach ($data as $item) {
            $barang = Barang::where('nama_barang', $item['nama_barang'])->first();

            $totalKeluar = (int) $item['keluar_ap']
                + (int) $item['keluar_rf']
                + (int) $item['keluar_mp']
                + (int) $item['keluar_pwk']
                + (int) $item['keluar_bdg']
                + (int) $item['keluar_racik'];

            $stokAkhir = ((int) $item['stok_awal'] + (int) $item['masuk_pabrik'] + (int) $item['masuk_cabang'])
                - $totalKeluar
                - (int) $item['retur_pabrik'];

            PerencanaanStok::updateOrCreate(
                [
                    'periode' => $periode,
                    'tipe_periode' => 'bulanan',
                    'nama_barang' => $item['nama_barang'],
                ],
                array_merge($item, [
                    'barang_id' => $barang?->id,
                    'total_keluar' => $totalKeluar,
                    'stok_akhir' => $stokAkhir,
                    'tanggal_mulai' => '2026-11-01',
                    'tanggal_selesai' => '2026-11-30',
                ])
            );
        }
    }
